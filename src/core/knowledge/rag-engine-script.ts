/**
 * The RAG engine script the cli writes to `.claude/rag/engine.mjs` (self-healed before each run) and
 * runs **as the agent** with the worker's `node` — never loaded into the cli process (the folder is
 * agent-writable). Node engine: transformers.js embeddings (q8 ONNX, mean-pooled, normalized) +
 * sqlite-vec on the built-in `node:sqlite`, packages from the pinned runtime in `.claude/rag/runtime`.
 * Downloads go through the egress proxy (undici `EnvHttpProxyAgent` + `NODE_USE_ENV_PROXY`).
 * Commands: `warm <model>` (download), `reindex`, `query <k> <kinds-csv>` (text in `RAG_QUERY`).
 * @adr 0489 @adr 0157
 */

/** Bumped when the index format changes — an index from another engine is reported `stale`. */
export const RAG_ENGINE_VERSION = "node-1";

/** The engine source (plain ESM, no build step). */
export const RAG_ENGINE_MJS = String.raw`// 4PM RAG engine (generated by the 4PM cli — do not edit; it is rewritten before every run).
import { createRequire } from "node:module";
import { lstat, readdir, readFile, realpath, writeFile, mkdir } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const ENGINE = "${RAG_ENGINE_VERSION}";
const ROOT = await realpath(".");
const BASE = join(ROOT, ".claude", "rag");
const RUNTIME = join(BASE, "runtime");
const MODELS = join(BASE, "models");
const DB = join(BASE, "index.db");
const MAX_CHUNKS = 5000;
const MAX_FILE = 1_000_000;
const SKIP = new Set(["node_modules", ".git", "dist", "build", ".next", "out", "coverage", ".turbo", "vendor", "venv", ".venv", "target"]);
const require = createRequire(join(RUNTIME, "package.json"));

/** Route fetch through the egress proxy the cli gives every agent run. */
async function useProxy() {
  try {
    const { EnvHttpProxyAgent, setGlobalDispatcher } = await import(require.resolve("undici"));
    if (process.env.HTTPS_PROXY || process.env.https_proxy) setGlobalDispatcher(new EnvHttpProxyAgent());
  } catch (e) {
    console.error("[engine] proxy setup failed:", e && e.message);
  }
}

/** Load transformers.js with its cache in the project volume (a cached model needs no network). */
async function transformers() {
  const t = await import(require.resolve("@huggingface/transformers"));
  t.env.cacheDir = MODELS;
  t.env.allowLocalModels = false;
  t.env.allowRemoteModels = true;
  return t;
}

/** A feature-extraction pipeline for the installed model. */
async function embedder(model) {
  const t = await transformers();
  return t.pipeline("feature-extraction", model, { dtype: "q8" });
}

/** Embed texts → number[][] (mean-pooled, normalized). */
async function embed(pipe, texts) {
  const out = await pipe(texts, { pooling: "mean", normalize: true });
  return out.tolist();
}

/** Open the index with sqlite-vec loaded. */
async function openDb() {
  const { DatabaseSync } = await import("node:sqlite");
  const sqliteVec = require("sqlite-vec");
  const db = new DatabaseSync(DB, { allowExtension: true });
  db.loadExtension(sqliteVec.getLoadablePath());
  db.enableLoadExtension(false);
  return db;
}

/** The installed model id. */
async function installedModel() {
  return (await readFile(join(BASE, ".installed"), "utf8")).trim();
}

/** Walk the project's .md files (no symlinks, no hidden or heavy dirs, real path inside the root). */
async function mdFiles() {
  const out = [];
  const stack = [ROOT];
  while (stack.length && out.length < 4000) {
    const dir = stack.pop();
    let entries;
    try { entries = await readdir(dir, { withFileTypes: true }); } catch { continue; }
    for (const e of entries) {
      if (e.isSymbolicLink()) continue;
      const full = join(dir, e.name);
      if (e.isDirectory()) { if (!e.name.startsWith(".") && !SKIP.has(e.name)) stack.push(full); continue; }
      if (e.isFile() && e.name.toLowerCase().endsWith(".md")) out.push(full);
    }
  }
  return out.filter((f) => f === ROOT || f.startsWith(ROOT + sep));
}

/** id / kind / title of a 4PM Doc Header (frontmatter), when present. */
function header(text) {
  const m = /^\uFEFF?---\r?\n([\s\S]{0,8192}?)\r?\n(?:---|\.\.\.)\s*(?:\r?\n|$)/.exec(text);
  if (!m) return {};
  const get = (k) => {
    const r = new RegExp("^" + k + "\\s*:\\s*(.+)$", "m").exec(m[1]);
    return r ? r[1].replace(/\s#.*$/, "").trim().replace(/^["']|["']$/g, "") : undefined;
  };
  return { id: get("id"), kind: get("kind"), title: get("title"), body: text.slice(m[0].length) };
}

/** (Re)build the index. */
async function reindex() {
  await useProxy();
  const model = await installedModel();
  const pipe = await embedder(model);
  const chunks = [];
  let docs = 0;
  for (const f of await mdFiles()) {
    const st = await lstat(f);
    if (!st.isFile() || st.size > MAX_FILE) continue;
    const text = await readFile(f, "utf8");
    const h = header(text);
    const body = h.body ?? text;
    const path = relative(ROOT, f).split(sep).join("/");
    if (/^(AI|USER)_[A-Z_]+\.md$/.test(path)) continue;
    docs++;
    for (let i = 0; i < body.length; i += 800) {
      const c = body.slice(i, i + 1000).trim();
      if (c.length > 20) chunks.push({ path, text: c, title: h.title ?? "", kind: h.kind ?? "" });
    }
    if (chunks.length >= MAX_CHUNKS) break;
  }
  const rows = chunks.slice(0, MAX_CHUNKS);
  const vectors = [];
  for (let i = 0; i < rows.length; i += 32) {
    vectors.push(...(await embed(pipe, rows.slice(i, i + 32).map((r) => (r.title ? r.title + "\n" : "") + r.text))));
    if (i % 320 === 0) console.log("[reindex] embedded " + Math.min(i + 32, rows.length) + "/" + rows.length);
  }
  const dim = vectors[0] ? vectors[0].length : 384;
  await mkdir(BASE, { recursive: true });
  const db = await openDb();
  db.exec("DROP TABLE IF EXISTS chunks");
  db.exec("CREATE VIRTUAL TABLE chunks USING vec0(embedding float[" + dim + "], +path text, +snippet text, +title text, +kind text)");
  const ins = db.prepare("INSERT INTO chunks(embedding, path, snippet, title, kind) VALUES (?, ?, ?, ?, ?)");
  db.exec("BEGIN");
  rows.forEach((r, i) => ins.run(new Uint8Array(new Float32Array(vectors[i]).buffer), r.path, r.text.slice(0, 600), r.title, r.kind));
  db.exec("COMMIT");
  db.close();
  const meta = { chunks: rows.length, docs, indexedAt: new Date().toISOString().slice(0, 19), model, engine: ENGINE };
  await writeFile(join(BASE, ".index.json"), JSON.stringify(meta));
  console.log("[reindex] DONE " + rows.length + " chunks from " + docs + " docs");
}

/** Query: print {results} as JSON on stdout. */
async function query(k, kinds) {
  const text = process.env.RAG_QUERY || "";
  const model = await installedModel();
  const pipe = await embedder(model);
  const [vec] = await embed(pipe, [text]);
  const db = await openDb();
  const want = kinds ? new Set(kinds.split(",").filter(Boolean)) : null;
  const fetchK = want ? Math.min(k * 6, 120) : k;
  const rows = db
    .prepare("SELECT path, snippet, title, kind, distance FROM chunks WHERE embedding MATCH ? AND k = ? ORDER BY distance")
    .all(new Uint8Array(new Float32Array(vec).buffer), fetchK);
  db.close();
  const results = rows
    .filter((r) => !want || want.has(r.kind))
    .slice(0, k)
    .map((r) => ({ path: r.path, snippet: r.snippet, score: Math.round((1 / (1 + Number(r.distance))) * 10000) / 10000, title: r.title || undefined, kind: r.kind || undefined }));
  process.stdout.write(JSON.stringify({ results }));
}

/** Download (warm) a model into the cache. */
async function warm(model) {
  await useProxy();
  const pipe = await embedder(model);
  await embed(pipe, ["warm up"]);
  console.log("[install] model ready: " + model);
}

const [cmd, a1, a2] = process.argv.slice(2);
try {
  if (cmd === "warm") await warm(a1);
  else if (cmd === "reindex") await reindex();
  else if (cmd === "query") await query(Math.min(Math.max(parseInt(a1 || "8", 10) || 8, 1), 20), a2 || "");
  else throw new Error("unknown command " + cmd);
} catch (e) {
  console.error("[engine] " + (e && e.stack ? e.stack : e));
  process.exit(1);
}
`;
