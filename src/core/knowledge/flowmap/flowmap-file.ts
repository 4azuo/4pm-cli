/**
 * The saved form of a flow map: a Markdown doc with a 4PM Doc Header (`kind: flow`, the doc sources under
 * `refs.uses`, every source pinned `path@commit`), the rendered SVG beside it, and the model in a fenced
 * ` ```json 4pm-flow ` block — so the graph sees the diagram as a doc and the file reads on any git host.
 * @adr 0698 @arch 0076
 */

/** Inputs of {@link flowMapMarkdown}. */
export interface FlowMapFileInput {
  id: string;
  title: string;
  features: string[];
  /** Doc ids of the doc sources. */
  uses: string[];
  generatedBy: string;
  sources: { path: string; commit: string }[];
  svgName: string;
  modelJson: string;
}

/** Quote a YAML scalar when it needs it. */
function yamlScalar(v: string): string {
  return /^[\w./@-][\w ./@()-]*$/.test(v) && !/:\s/.test(v) ? v : JSON.stringify(v);
}

/** The `.flow.md` text. */
export function flowMapMarkdown(f: FlowMapFileInput): string {
  const lines = [
    "---",
    `id: ${f.id}`,
    "kind: flow",
    `title: ${yamlScalar(f.title)}`,
  ];
  if (f.features.length) lines.push(`feature: [${f.features.map(yamlScalar).join(", ")}]`);
  if (f.uses.length) lines.push("refs:", `  uses: [${f.uses.join(", ")}]`);
  lines.push(`generatedBy: ${yamlScalar(f.generatedBy)}`);
  if (f.sources.length) {
    lines.push("sources:");
    for (const s of f.sources) lines.push(`  - ${s.path}@${s.commit.slice(0, 12)}`);
  }
  lines.push("---", `# ${f.title}`, "", `![${f.title.replace(/[[\]]/g, "")}](${f.svgName})`, "", "<!-- Generated by 4PM flow maps; edit the diagram in 4PM, not here. -->", "", "```json 4pm-flow", f.modelJson.trim(), "```", "");
  return lines.join("\n");
}

/** The SVG file name beside a `.md` file name. */
export function svgNameOf(fileName: string): string {
  return fileName.replace(/\.md$/i, "") + ".svg";
}
